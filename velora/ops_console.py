"""Operational dashboard, alert evaluation and metrics export for Velora."""
from __future__ import annotations
import html
import json
import os
from datetime import datetime, timezone
from pathlib import Path

from .monitoring import monitoring_snapshot, recovery_report
from .operations import health_snapshot
from .workspace import Workspace, WorkspaceError


def operations_snapshot(ws: Workspace) -> dict:
    health = health_snapshot(ws)
    monitor = monitoring_snapshot(ws)
    recovery = recovery_report(ws)
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "workspace": str(ws.root),
        "overall": "fail" if monitor.get("status") == "fail" else (
            "warning" if health.get("status") == "warning" or recovery.get("status") in {"stale", "unknown"} else "ok"),
        "health": health,
        "databases": monitor.get("databases", {}),
        "recovery": recovery,
    }


def render_dashboard(snapshot: dict) -> str:
    """Render a self-contained dashboard; all dynamic content is HTML escaped."""
    status = snapshot.get("overall", "unknown")
    health = snapshot.get("health", {})
    db = snapshot.get("databases", {})
    recovery = snapshot.get("recovery", {})
    cards = [
        ("Overall status", status), ("Sites", health.get("sites", {}).get("count", 0)),
        ("Applications", len(health.get("applications", {}).get("registered", []))),
        ("Databases healthy", f"{db.get('healthy', 0)} / {db.get('checked', 0)}"),
        ("Free storage", f"{health.get('storage', {}).get('free_percent', 0)}%"),
        ("Recovery status", recovery.get("status", "unknown")),
        ("Estimated RPO", f"{recovery.get('estimated_rpo_hours')} hours" if recovery.get("estimated_rpo_hours") is not None else "Unknown"),
        ("Recent log errors", health.get("logs", {}).get("recent_error_lines", 0)),
    ]
    card_html = "\n".join(f'<article class="card"><span>{html.escape(str(k))}</span><strong>{html.escape(str(v))}</strong></article>' for k, v in cards)
    probes = "\n".join(f'<tr><td>{html.escape(str(p.get("name", "unknown")))}</td><td>{html.escape(str(p.get("status", "unknown")))}</td></tr>' for p in db.get("probes", []))
    return f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Velora Operations</title>
<style>body{{font:15px system-ui;margin:0;background:#f4f6fa;color:#172033}}header{{background:#14213d;color:white;padding:24px 5vw}}main{{max-width:1100px;margin:28px auto;padding:0 20px}}.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(190px,1fr));gap:14px}}.card,section{{background:white;border:1px solid #e3e8f0;border-radius:12px;padding:18px}}.card span{{display:block;color:#65718a;font-size:13px}}.card strong{{display:block;font-size:24px;margin-top:8px;text-transform:capitalize}}table{{width:100%;border-collapse:collapse}}td,th{{text-align:left;padding:10px;border-bottom:1px solid #e5e9f0}}small{{color:#64748b}}</style></head><body><header><h1>Velora Operations</h1><div>Workspace: {html.escape(str(snapshot.get('workspace','')))}</div><small>Generated: {html.escape(str(snapshot.get('generated_at','')))}</small></header><main><div class="grid">{card_html}</div><section style="margin-top:20px"><h2>Database health</h2><table><thead><tr><th>Database</th><th>Status</th></tr></thead><tbody>{probes or '<tr><td colspan="2">No database probes available</td></tr>'}</tbody></table></section><p><small>Generated by Velora. This report is a point-in-time snapshot, not a live monitoring connection.</small></p></main></body></html>'''


def write_dashboard(ws: Workspace, destination: str | Path | None = None) -> Path:
    target = Path(destination) if destination else ws.root / "reports" / "operations-dashboard.html"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_dashboard(operations_snapshot(ws)), encoding="utf-8")
    return target


DEFAULT_ALERT_POLICY = {
    "version": 1, "enabled": True,
    "rules": {"disk_free_below_percent": 10, "database_failures_above": 0,
              "backup_stale_after_hours": 26, "log_errors_above": 20},
}


def configure_alert_policy(ws: Workspace, rules: dict | None = None) -> dict:
    policy = dict(DEFAULT_ALERT_POLICY)
    if rules:
        policy["rules"] = {**DEFAULT_ALERT_POLICY["rules"], **rules}
    for key, value in policy["rules"].items():
        if isinstance(value, bool) or not isinstance(value, (int, float)) or value < 0:
            raise WorkspaceError(f"Alert threshold {key} must be a non-negative number")
    path = ws.root / "config" / "alert-policy.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(policy, indent=2) + "\n", encoding="utf-8")
    os.chmod(tmp, 0o600); os.replace(tmp, path)
    return policy


def evaluate_alerts(ws: Workspace, *, snapshot: dict | None = None) -> dict:
    path = ws.root / "config" / "alert-policy.json"
    if not path.exists():
        policy = configure_alert_policy(ws)
    else:
        try: policy = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc: raise WorkspaceError(f"Alert policy is invalid: {exc}") from exc
    if policy.get("version") != 1 or not isinstance(policy.get("rules"), dict):
        raise WorkspaceError("Alert policy is invalid; reconfigure it")
    snap = snapshot or operations_snapshot(ws)
    rules = policy["rules"]
    health, db, recovery = snap.get("health", {}), snap.get("databases", {}), snap.get("recovery", {})
    checks = [
        ("disk_capacity", health.get("storage", {}).get("free_percent", 100) < rules.get("disk_free_below_percent", 10),
         f"Free disk space is {health.get('storage', {}).get('free_percent', 'unknown')}%"),
        ("database_unavailable", db.get("checked", 0) - db.get("healthy", 0) > rules.get("database_failures_above", 0),
         f"Database failures: {db.get('checked', 0) - db.get('healthy', 0)}"),
        ("backup_stale", recovery.get("status") in {"stale", "unknown"} or (recovery.get("estimated_rpo_hours") is not None and recovery["estimated_rpo_hours"] > rules.get("backup_stale_after_hours", 26)),
         f"Backup freshness status: {recovery.get('status', 'unknown')}"),
        ("log_errors", health.get("logs", {}).get("recent_error_lines", 0) > rules.get("log_errors_above", 20),
         f"Recent error lines: {health.get('logs', {}).get('recent_error_lines', 0)}"),
    ]
    active = [{"code": code, "severity": "warning" if code in {"disk_capacity", "backup_stale", "log_errors"} else "critical", "message": message}
              for code, triggered, message in checks if triggered and policy.get("enabled", True)]
    result = {"generated_at": datetime.now(timezone.utc).isoformat(), "active_count": len(active), "alerts": active}
    audit = ws.root / "logs" / "operations-alerts.jsonl"
    audit.parent.mkdir(parents=True, exist_ok=True)
    previous = set()
    state = ws.root / "config" / "alert-state.json"
    if state.exists():
        try: previous = set(json.loads(state.read_text()).get("active_codes", []))
        except (OSError, json.JSONDecodeError): previous = set()
    current = {a["code"] for a in active}
    transitions = [{"event": "triggered", **a} for a in active if a["code"] not in previous]
    transitions += [{"event": "resolved", "code": code, "message": "Condition cleared"} for code in sorted(previous - current)]
    with audit.open("a", encoding="utf-8") as stream:
        for event in transitions: stream.write(json.dumps({"timestamp": result["generated_at"], **event}) + "\n")
    state.parent.mkdir(parents=True, exist_ok=True)
    tmp = state.with_suffix(".tmp"); tmp.write_text(json.dumps({"active_codes": sorted(current)}, indent=2) + "\n")
    os.chmod(tmp, 0o600); os.replace(tmp, state)
    result["transitions"] = transitions
    return result


def collect_metrics(ws: Workspace, *, snapshot: dict | None = None) -> dict[str, float]:
    snap = snapshot or operations_snapshot(ws)
    health, db, recovery = snap.get("health", {}), snap.get("databases", {}), snap.get("recovery", {})
    disk = health.get("storage", {})
    metrics = {
        "velora_sites_total": float(health.get("sites", {}).get("count", 0)),
        "velora_applications_total": float(len(health.get("applications", {}).get("registered", []))),
        "velora_databases_checked_total": float(db.get("checked", 0)),
        "velora_databases_healthy": float(db.get("healthy", 0)),
        "velora_database_failures": float(max(0, db.get("checked", 0) - db.get("healthy", 0))),
        "velora_disk_total_bytes": float(disk.get("total_bytes", 0)),
        "velora_disk_used_bytes": float(disk.get("used_bytes", 0)),
        "velora_disk_free_bytes": float(disk.get("free_bytes", 0)),
        "velora_disk_free_percent": float(disk.get("free_percent", 0)),
        "velora_log_error_lines": float(health.get("logs", {}).get("recent_error_lines", 0)),
        "velora_backup_rpo_hours": float(recovery.get("estimated_rpo_hours") or 0),
        "velora_backup_files": float(recovery.get("backup_file_count", 0)),
    }
    try:
        load = os.getloadavg()
        metrics.update({f"velora_host_load{idx+1}": float(value) for idx, value in enumerate(load)})
    except (AttributeError, OSError): pass
    try:
        page_size = os.sysconf("SC_PAGE_SIZE"); pages = os.sysconf("SC_PHYS_PAGES"); available = os.sysconf("SC_AVPHYS_PAGES")
        metrics["velora_host_memory_total_bytes"] = float(page_size * pages)
        metrics["velora_host_memory_available_bytes"] = float(page_size * available)
    except (ValueError, OSError, AttributeError): pass
    return metrics


def prometheus_text(metrics: dict[str, float]) -> str:
    lines = ["# HELP velora_platform_up Whether Velora metrics collection completed.", "# TYPE velora_platform_up gauge", "velora_platform_up 1"]
    for name, value in sorted(metrics.items()):
        safe = "".join(c if c.isalnum() or c in "_:" else "_" for c in name)
        lines.extend([f"# TYPE {safe} gauge", f"{safe} {value:g}"])
    return "\n".join(lines) + "\n"
